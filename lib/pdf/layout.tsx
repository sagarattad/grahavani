/**
 * The PDF font (Noto Sans, Latin subset) has no other scripts and no arrows or
 * ≤ / ≥: drop other scripts ("Pasha (पाश)" → "Pasha"), spell those symbols in
 * ASCII, and keep everything the font has, including the minus sign U+2212.
 */
export const latin = (text: string) =>
  text
    .replace(/\s*\([^()\x00-\u024F]+\)/g, "")
    .replace(/→/g, "->")
    .replace(/≤/g, "<=")
    .replace(/≥/g, ">=")
    .replace(/[^\x00-\u024F\u2000-\u206F\u20AC\u2122\u2191\u2193\u2212\u2215]/g, "")
    .trim();

export type PdfPerson = { name: string; birthDate: string; birthTime: string; placeLabel: string };
export type Reading = Record<string, unknown>;

export function PdfDoc({
  title,
  heading,
  attributions,
  children,
}: {
  title: string;
  heading: ReactNode;
  attributions: Attribution[];
  children: ReactNode;
}) {
  const t = getT();
  const citation = attributions[0]?.citation.replace(/ Please credit.*$/, "") ?? "";
  const generated = dateOnly(new Date().toISOString());
  return (
    <Document title={title} author="Grahavani" creator="Grahavani" producer="Grahavani">
      <Page size="A4" style={s.page} wrap>
        <Text style={s.brand}>Grahavani</Text>
        {heading}
        {children}
        <Text style={s.footer} fixed>
          {citation} kundlit.com · {t("app.disclaimer")}
        </Text>
        <Text
          style={s.pageNumber}
          fixed
          render={({ pageNumber, totalPages }) => `Generated by Grahavani on ${generated} · Page ${pageNumber} of ${totalPages}`}
        />
      </Page>
    </Document>
  );
}

export function PersonLine({ p, role }: { p: PdfPerson; role?: string }) {
  return (
    <View style={{ marginTop: 3 }}>
      <Text>
        <Text style={s.bold}>{role ? `${role}: ${p.name}` : p.name}</Text>
        {"  "}
        {birthDateTime(p.birthDate, p.birthTime)}
      </Text>
      <Text style={s.muted}>{p.placeLabel}</Text>
    </View>
  );
}

/** `keepTogether` moves a short section to the next page instead of splitting it. */
export function Section({
  title,
  children,
  breakBefore,
  keepTogether,
}: {
  title: string;
  children: ReactNode;
  breakBefore?: boolean;
  keepTogether?: boolean;
}) {
  return (
    <View style={s.section} break={breakBefore} wrap={!keepTogether}>
      <Text style={s.h2} minPresenceAhead={120}>
        {title}
      </Text>
      {children}
    </View>
  );
}

export function KeyValues({ rows }: { rows: [string, string][] }) {
  return (
    <View>
      {rows.map(([k, v]) => (
        <View key={k} style={[s.row, { paddingVertical: 1.5 }]}>
          <Text style={[s.muted, { width: 130 }]}>{k}</Text>
          <Text style={[s.bold, { flex: 1 }]}>{v}</Text>
        </View>
      ))}
    </View>
  );
}

/** Columns: [header, width (flex), align]. */
export function Table({ cols, rows }: { cols: [string, number, ("left" | "right" | "center")?][]; rows: string[][] }) {
  return (
    <View>
      <View style={s.row} fixed={false}>
        {cols.map(([h, w, a]) => (
          <Text key={h} style={[s.th, { flex: w, textAlign: a ?? "left" }]}>
            {h}
          </Text>
        ))}
      </View>
      {rows.map((r, i) => (
        <View key={i} style={s.row} wrap={false}>
          {r.map((cell, j) => (
            <Text key={j} style={[s.td, { flex: cols[j][1], textAlign: cols[j][2] ?? "left" }]}>
              {cell}
            </Text>
          ))}
        </View>
      ))}
    </View>
  );
}

type KootItem = { koot?: string; earned?: number; max?: number; explanation?: string };

export function ReadingSection({ kind, reading }: { kind: ReadingKind; reading: Reading | null }) {
  return (
    <Section title="AI reading">
      {!reading ? (
        <Text style={s.muted}>
          No AI reading yet. Tap “Get reading” on the Grahavani page, then download the PDF again to include it.
        </Text>
      ) : (
        <View>
          {READING_CARDS[kind].map(({ key, title }) => {
            const value = reading[key];
            if (value === undefined) return null;
            return (
              <View key={key} style={s.card} wrap={false}>
                <Text style={[s.bold, { marginBottom: 2 }]}>{title}</Text>
                {Array.isArray(value) ? (
                  (value as KootItem[]).map((k, i) => (
                    <Text key={i} style={{ marginTop: 2 }}>
                      <Text style={s.bold}>
                        {k.koot} · {k.earned} / {k.max}:{" "}
                      </Text>
                      {latin(k.explanation ?? "")}
                    </Text>
                  ))
                ) : (
                  <Text>{latin(String(value))}</Text>
                )}
              </View>
            );
          })}
          <Text style={[s.small, { marginTop: 6 }]}>
            AI-generated from the computed data only. Traditional interpretation; not medical, legal or financial advice.
          </Text>
        </View>
      )}
    </Section>
  );
}

export function NoteBox({ title, lines }: { title: string; lines: string[] }) {
  if (!lines.length) return null;
  return (
    <View style={s.note} wrap={false}>
      <Text style={[s.bold, { color: C.warn }]}>{title}</Text>
      {lines.map((l) => (
        <Text key={l}>{l}</Text>
      ))}
    </View>
  );
}
